"""Catalog of ready-to-render field scenarios.

Every scenario is a plain dict (JSON-serialisable) so custom scenarios can be
written as JSON files and passed to ``scripts/generate.py --scenario-file``.

Schema (all keys optional except name / crops):

    name, title, description, tasks: [..], seed
    field:       {width, length}                         metres; rows run along +y
    crops:       [{crop, stage | stage_mix, row_spacing, plant_spacing, gap_rate,
                   size_cv, stunted_rate, lateral_jitter, opts, variants}]
    row_pattern: [crop indices per row, cycled]          strip intercropping
    terrain:     {soil, wetness, slope_deg, slope_dir_deg, undulation, roughness,
                  row_curvature, curvature_wavelength, tracks, tramlines, bed,
                  ridge, mulch, paddy, water_level, puddles, headland, resolution}
    weeds:       {density (per m2), species: {name: weight}, stage | stages,
                  intra_row, patchiness}
    ground_cover:{density, dry, height, row_clearance, headland, where}
    props:       [{type: trellis|stakes|drip_tape|sprinklers|rocks|crates|buckets|
                   tools|hoses|people|residue, ...}]
    environment: {lighting, fog, exposure, background, headlight}
    cameras:     [front|front_low|nadir|side|drone|drone_oblique|overview | {name, base, ...}]
    robot:       {camera_height, camera_pitch, path: auto|furrow|bed|track, path_index}
"""

import copy

_BASE = dict(
    seed=0,
    field=dict(width=9.0, length=16.0),
    terrain=dict(soil="loam", wetness=0.15, undulation=0.03),
    weeds=dict(density=0.6, species={"pigweed": 1, "crabgrass": 1, "dandelion": 0.5}, stage="small",
               intra_row=0.25, patchiness=0.4),
    props=[],
    environment=dict(lighting="morning", background="treeline"),
    cameras=["front", "nadir", "overview"],
    robot=dict(),
)


def _merge(base, over):
    out = copy.deepcopy(base)
    for k, v in over.items():
        if isinstance(v, dict) and isinstance(out.get(k), dict) and k not in ("weeds",):
            out[k] = _merge(out[k], v)
        else:
            out[k] = copy.deepcopy(v)
    return out


def S(name, title, tasks, crops, **kw):
    sc = dict(name=name, title=title, tasks=tasks, crops=crops)
    sc.update(kw)
    sc = _merge(_BASE, sc)
    sc["seed"] = kw.get("seed", sum(map(ord, name)) * 7919 % 100003)  # stable per name
    return sc


